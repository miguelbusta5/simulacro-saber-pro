'use strict';

const { Pool } = require('pg');

const URL_BD = process.env.DATABASE_URL;
if (!URL_BD) {
  throw new Error(
    'Falta la variable DATABASE_URL con la cadena de conexión de Postgres. ' +
      'Copia .env.example a .env y pega ahí la URI de tu proyecto de Supabase.'
  );
}

// Permite correr las pruebas contra un esquema aparte sin tocar los datos reales.
const ESQUEMA = process.env.SIMULACRO_ESQUEMA || 'public';
if (!/^[a-z_][a-z0-9_]*$/.test(ESQUEMA)) {
  throw new Error(`Nombre de esquema inválido: ${ESQUEMA}`);
}

const esLocal = /localhost|127\.0\.0\.1/.test(URL_BD);

const pool = new Pool({
  connectionString: URL_BD,
  // Por esta conexión viajan hashes de contraseñas, tokens de sesión y las
  // respuestas correctas del examen, así que se valida el certificado del
  // servidor: sin validar, cualquiera que intercepte la red podría hacerse pasar
  // por la base de datos. Neon y Supabase usan certificados de una CA pública y
  // la validación funciona sin configuración extra. La variable de escape es
  // para un Postgres propio con certificado autofirmado.
  ssl: esLocal ? false : { rejectUnauthorized: process.env.PG_SSL_SIN_VERIFICAR !== '1' },
  max: Number(process.env.PG_MAX_CONEXIONES) || 8,
  // El search_path se fija al abrir la conexión, no con un SET posterior: así no
  // hay ventana en la que una consulta apunte al esquema equivocado. Solo hace
  // falta para las pruebas; en producción el esquema es "public", que ya es el
  // valor por defecto, y así no se envía un parámetro que algunos poolers rechazan.
  ...(ESQUEMA === 'public' ? {} : { options: `-c search_path=${ESQUEMA}` }),
});

pool.on('error', (e) => {
  console.error('Error inesperado en el pool de Postgres:', e.message);
});

// ---------- helpers de consulta ----------

async function consulta(sql, params = [], cliente = pool) {
  const { rows } = await cliente.query(sql, params);
  return rows;
}

async function uno(sql, params = [], cliente = pool) {
  const { rows } = await cliente.query(sql, params);
  return rows[0] ?? null;
}

async function ejecutar(sql, params = [], cliente = pool) {
  return cliente.query(sql, params);
}

// Ejecuta fn dentro de una transacción sobre un mismo cliente del pool.
// fn recibe el cliente, que debe pasarse a consulta/uno/ejecutar.
async function enTransaccion(fn) {
  const cliente = await pool.connect();
  try {
    await cliente.query('BEGIN');
    const resultado = await fn(cliente);
    await cliente.query('COMMIT');
    return resultado;
  } catch (e) {
    await cliente.query('ROLLBACK');
    throw e;
  } finally {
    cliente.release();
  }
}

// ---------- esquema ----------

const DDL = `
CREATE TABLE IF NOT EXISTS usuarios (
  id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario   TEXT NOT NULL,
  nombre    TEXT NOT NULL DEFAULT '',
  pass_hash TEXT NOT NULL,
  pass_salt TEXT NOT NULL,
  creado_en TEXT NOT NULL
);
-- El nombre de usuario no distingue mayúsculas.
CREATE UNIQUE INDEX IF NOT EXISTS idx_usuario_unico ON usuarios (lower(usuario));

CREATE TABLE IF NOT EXISTS sesiones (
  token     TEXT PRIMARY KEY,
  user_id   INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  creado_en TEXT NOT NULL,
  expira_en TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_sesiones_user ON sesiones(user_id);

-- Texto, tabla o gráfica compartida por varias preguntas del mismo bloque.
CREATE TABLE IF NOT EXISTS contextos (
  id        TEXT PRIMARY KEY,
  modulo    TEXT NOT NULL,
  titulo    TEXT NOT NULL DEFAULT '',
  contenido TEXT NOT NULL,
  fuente    TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS preguntas (
  id                          TEXT PRIMARY KEY,
  modulo                      TEXT NOT NULL,
  competencia                 TEXT NOT NULL,
  tema                        TEXT NOT NULL,
  dificultad                  INTEGER NOT NULL DEFAULT 2,
  contexto_id                 TEXT REFERENCES contextos(id) ON DELETE SET NULL,
  enunciado                   TEXT NOT NULL,
  opciones                    TEXT NOT NULL,
  correcta                    TEXT NOT NULL,
  justificacion               TEXT NOT NULL,
  justificaciones_incorrectas TEXT NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_preguntas_modulo ON preguntas(modulo);
CREATE INDEX IF NOT EXISTS idx_preguntas_comp ON preguntas(modulo, competencia);

CREATE TABLE IF NOT EXISTS intentos (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  estado        TEXT NOT NULL CHECK (estado IN ('en_curso','finalizado')),
  motivo_cierre TEXT NOT NULL DEFAULT '',
  iniciado_en   TEXT NOT NULL,
  vence_en      TEXT NOT NULL,
  finalizado_en TEXT
);
-- Garantiza a nivel de base de datos un solo intento activo por usuario.
CREATE UNIQUE INDEX IF NOT EXISTS idx_un_intento_activo
  ON intentos(user_id) WHERE estado = 'en_curso';
CREATE INDEX IF NOT EXISTS idx_intentos_user ON intentos(user_id, iniciado_en DESC);

CREATE TABLE IF NOT EXISTS intento_preguntas (
  intento_id  INTEGER NOT NULL REFERENCES intentos(id) ON DELETE CASCADE,
  orden       INTEGER NOT NULL,
  pregunta_id TEXT NOT NULL REFERENCES preguntas(id),
  modulo      TEXT NOT NULL,
  PRIMARY KEY (intento_id, orden)
);
CREATE INDEX IF NOT EXISTS idx_ip_pregunta ON intento_preguntas(pregunta_id);

CREATE TABLE IF NOT EXISTS respuestas (
  intento_id    INTEGER NOT NULL REFERENCES intentos(id) ON DELETE CASCADE,
  pregunta_id   TEXT NOT NULL,
  opcion        TEXT,
  marcada       INTEGER NOT NULL DEFAULT 0,
  respondido_en TEXT NOT NULL,
  PRIMARY KEY (intento_id, pregunta_id)
);

CREATE TABLE IF NOT EXISTS resultados (
  intento_id INTEGER NOT NULL REFERENCES intentos(id) ON DELETE CASCADE,
  modulo     TEXT NOT NULL,
  aciertos   INTEGER NOT NULL,
  total      INTEGER NOT NULL,
  puntaje    INTEGER NOT NULL,
  nivel      TEXT NOT NULL,
  PRIMARY KEY (intento_id, modulo)
);
`;

// Columnas añadidas después de la primera versión. Van aparte del bloque de
// CREATE TABLE porque ese solo actúa cuando la tabla no existe, y estas tienen
// que aplicarse también sobre una base que ya está en uso. Los valores por
// defecto etiquetan correctamente lo que ya hay: todo lo anterior es de la V1 y
// todos los usuarios existentes son estudiantes.
const MIGRACIONES = `
ALTER TABLE usuarios  ADD COLUMN IF NOT EXISTS rol     TEXT NOT NULL DEFAULT 'estudiante';
ALTER TABLE preguntas ADD COLUMN IF NOT EXISTS version TEXT NOT NULL DEFAULT 'v1';
ALTER TABLE contextos ADD COLUMN IF NOT EXISTS version TEXT NOT NULL DEFAULT 'v1';
ALTER TABLE intentos  ADD COLUMN IF NOT EXISTS version TEXT NOT NULL DEFAULT 'v1';

CREATE INDEX IF NOT EXISTS idx_preguntas_version
  ON preguntas(version, modulo, competencia);
CREATE INDEX IF NOT EXISTS idx_usuarios_rol ON usuarios(rol) WHERE rol <> 'estudiante';
`;

// Crea el esquema si no existe. Es idempotente: se puede llamar en cada arranque.
async function inicializar() {
  if (ESQUEMA !== 'public') {
    await pool.query(`CREATE SCHEMA IF NOT EXISTS ${ESQUEMA}`);
  }
  await pool.query(DDL);
  await pool.query(MIGRACIONES);
}

function ahora() {
  return new Date().toISOString();
}

async function cerrar() {
  await pool.end();
}

module.exports = { pool, consulta, uno, ejecutar, enTransaccion, inicializar, ahora, cerrar, ESQUEMA };
